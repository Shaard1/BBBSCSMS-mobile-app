// Run from the mobile project: node tool/generate_brand_motion.cjs
// Then format lib/widgets/brand_motion_geometry.dart with dart format.
// The app uses precomputed contours so matching/resampling never runs at startup.
const fs = require('node:fs');

const source = fs.readFileSync('lib/assets/bancao-connect-mark.svg', 'utf8');
const paths = [...source.matchAll(/<path fill="([^"]+)" d="([^"]+)"/g)];
if (paths.length !== 2) throw new Error('Expected the two community emblem colors.');
const blue = paths[0][2].match(/M[^Z]+Z/g);
const teal = paths[1][2].match(/M[^Z]+Z/g);
if (blue.length !== 4 || teal.length !== 2) {
  throw new Error('The emblem contours changed; review the figure mapping.');
}
const pointCount = 180;
const mix = (a, b, t) => a + (b - a) * t;
const numericPath = d => d.match(/-?\d+(?:\.\d+)?/g).map(Number);

function sampleQuadratic(path) {
  const coordinates = numericPath(path);
  let previous = coordinates.slice(0, 2);
  const points = [previous];
  for (let i = 2; i < coordinates.length; i += 4) {
    const control = coordinates.slice(i, i + 2);
    const end = coordinates.slice(i + 2, i + 4);
    for (let step = 1; step <= 8; step++) {
      const t = step / 8, u = 1 - t;
      points.push([
        u*u*previous[0] + 2*u*t*control[0] + t*t*end[0],
        u*u*previous[1] + 2*u*t*control[1] + t*t*end[1],
      ]);
    }
    previous = end;
  }
  return points;
}

function resample(points) {
  const lengths = [0];
  for (let i = 1; i <= points.length; i++) {
    const a = points[i - 1], b = points[i % points.length];
    lengths.push(lengths.at(-1) + Math.hypot(b[0] - a[0], b[1] - a[1]));
  }
  let segment = 0;
  return Array.from({length: pointCount}, (_, i) => {
    const distance = lengths.at(-1) * i / pointCount;
    while (lengths[segment + 1] < distance) segment++;
    const a = points[segment], b = points[(segment + 1) % points.length];
    const fraction = (distance - lengths[segment]) /
      (lengths[segment + 1] - lengths[segment] || 1);
    return [mix(a[0], b[0], fraction), mix(a[1], b[1], fraction)];
  });
}

// Match contour direction and starting point to avoid folds during the morph.
function align(seed, target) {
  let minimum = Infinity, best;
  for (const reverse of [false, true]) {
    for (let offset = 0; offset < seed.length; offset++) {
      let error = 0;
      for (let i = 0; i < seed.length; i++) {
        const a = seed[(offset + (reverse ? -i : i) + seed.length) % seed.length];
        const b = target[i];
        error += (a[0] - b[0])**2 + (a[1] - b[1])**2;
      }
      if (error < minimum) {
        minimum = error;
        best = {reverse, offset};
      }
    }
  }
  return target.map((_, i) => seed[
    (best.offset + (best.reverse ? -i : i) + seed.length) % seed.length
  ]);
}

function ribbon(angle) {
  const radius = 107, halfWidth = 32;
  const start = angle - .72, end = angle + .72;
  const points = [];
  const put = (a, r) => points.push([161 + Math.cos(a)*r, 156 + Math.sin(a)*r]);
  for (let i = 0; i <= 48; i++) put(mix(start, end, i / 48), radius + halfWidth);
  const ex = 161 + Math.cos(end)*radius, ey = 156 + Math.sin(end)*radius;
  for (let i = 1; i <= 24; i++) {
    const a = end + i / 24 * Math.PI;
    points.push([ex + Math.cos(a)*halfWidth, ey + Math.sin(a)*halfWidth]);
  }
  for (let i = 1; i <= 48; i++) put(mix(end, start, i / 48), radius - halfWidth);
  const sx = 161 + Math.cos(start)*radius, sy = 156 + Math.sin(start)*radius;
  for (let i = 1; i < 24; i++) {
    const a = start + Math.PI + i / 24 * Math.PI;
    points.push([sx + Math.cos(a)*halfWidth, sy + Math.sin(a)*halfWidth]);
  }
  return resample(points);
}

const figures = [
  {body: blue[1], head: blue[0], angle: -Math.PI / 2, headCenter: [161, 39]},
  {body: blue[2], head: blue[3], angle: 5*Math.PI / 6, headCenter: [38, 178]},
  {body: teal[0], head: teal[1], angle: Math.PI / 6, headCenter: [283, 178]},
].map(figure => {
  const outline = resample(sampleQuadratic(figure.body));
  const arc = align(ribbon(figure.angle), outline);
  const cx = arc.reduce((sum, p) => sum + p[0], 0) / arc.length;
  const cy = arc.reduce((sum, p) => sum + p[1], 0) / arc.length;
  const circle = align(Array.from({length: pointCount}, (_, i) => [
    cx + Math.cos(i / pointCount * Math.PI * 2)*75,
    cy + Math.sin(i / pointCount * Math.PI * 2)*75,
  ]), arc);
  return {...figure, outline, arc, circle, cx, cy};
});

const number = value => Number(value.toFixed(4)).toString();
function doubles(name, values) {
  let result = `    ${name}: [\n`;
  for (let i = 0; i < values.length; i += 12) {
    result += '      ' + values.slice(i, i + 12).map(number).join(', ') + ',\n';
  }
  return result + '    ],\n';
}
let dart = `// Generated by tool/generate_brand_motion.cjs from lib/assets/bancao-connect-mark.svg.
// Edit the generator or source emblem, then regenerate this geometry.

class BrandMotionShape {
  const BrandMotionShape({required this.cx, required this.cy, required this.headX, required this.headY, required this.circle, required this.arc, required this.outline, required this.body, required this.head});
  final double cx, cy, headX, headY;
  final List<double> circle, arc, outline, body, head;
}

const brandMotionShapes = <BrandMotionShape>[
`;
for (const figure of figures) {
  dart += `  BrandMotionShape(\n    cx: ${number(figure.cx)}, cy: ${number(figure.cy)}, headX: ${figure.headCenter[0]}, headY: ${figure.headCenter[1]},\n`;
  for (const name of ['circle', 'arc', 'outline']) dart += doubles(name, figure[name].flat());
  dart += doubles('body', numericPath(figure.body));
  dart += doubles('head', numericPath(figure.head));
  dart += '  ),\n';
}
dart += '];\n';
fs.writeFileSync('lib/widgets/brand_motion_geometry.dart', dart);
console.log('Generated native logo geometry.');
